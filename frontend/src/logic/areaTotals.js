/**
 * 전형요소 만점 합계 — 순수 함수.
 *
 * AreasTab.vue 의 `totalMaxScore` computed 를 옮겼다. 태그 `0.2.21` 시점 원본과
 * 대조해 동치임을 확인했다(2026-09-21 코드 감사). 한 줄짜리라
 * 따로 테스트할 것이 많지는 않지만, 옮긴 이유는 테스트가 아니라 **손복사 제거**다:
 * `tools/oracle/front_check.mjs` §6 이 정밀도를 검사하면서 같은 식을 손으로 베껴
 * 쓰고 있었다. 이제 오라클이 이 함수를 그대로 호출하므로, 합산 방식이 바뀌면
 * 오라클이 바로 안다.
 *
 * **입력은 백엔드가 직렬화한 f64 점수다.** 백엔드는 ×100000 정수로 계산·저장하고
 * JSON 으로 내보낼 때 나눈다(Score newtype). 프론트는 그 값을 더하기만 한다 —
 * 여기서 ÷100000 을 하지 않는다(CLAUDE.md 규칙 1).
 *
 * 그래서 이 합산은 부동소수점 덧셈이고, 항 수가 많아지면 오차가 생길 수 있다.
 * 표시는 `formatScore` 가 소수 5자리까지만 보여 주므로 실사용 범위에서는 드러나지
 * 않는데, 그 "드러나지 않음"을 오라클 §6 이 BigInt 정확값과 대조해 확인한다.
 */
export function totalMaxScore(areas) {
  return areas.reduce((sum, a) => sum + a.max_score, 0)
}
